extern "C" void kmain(u32 magic, multiboot_info* mb) {
    if (magic != 0x2BADB002) {
        // Ошибка загрузчика (не Multiboot)
        for(;;);
    }

    gfx::init(mb);
    mouse::init();
    
    for (;;) {
        draw_desktop();
        draw_mouse_cursor(mouse::x, mouse::y);
        
        // Обработка мыши
        u8 st = inb(0x64);
        if (st & 1) {
            u8 b = inb(0x60);
            if (st & 0x20) mouse::feed(b);
        }
        
        // Задержка
        for (volatile int i = 0; i < 500000; i++); 
    }
}
