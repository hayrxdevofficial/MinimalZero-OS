    void draw_char(int x, int y, char c, u32 color) {
        if (c < 32 || c > 127) return;
        int idx = c - 32;
        for (int j = 0; j < 8; j++) {
            u8 row = font8x8[idx][j];
            for (int i = 0; i < 8; i++) {
                if (row & (1 << i)) put_pixel(x + i, y + j, color);
            }
        }
    }

    void draw_text(int x, int y, const char* str, u32 color) {
        while (*str) {
            draw_char(x, y, *str++, color);
            x += 8;
        }
    }
