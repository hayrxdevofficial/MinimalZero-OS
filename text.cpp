void draw_char(char c, int x, int y, u32 color, int scale) {
    if (c < 32 || c > 126) c = '?';
    const u8* g = font8x8[c - 32];
    for (int r = 0; r < 8; r++)
        for (int cl = 0; cl < 8; cl++)
            if (g[r] & (1 << (7 - cl))) {
                if (scale == 1) gfx::put(x + cl, y + r, color);
                else gfx::rect(x + cl * scale, y + r * scale, scale, scale, color);
            }
}

void draw(const char* s, int x, int y, u32 color, int scale) {
    while (*s) { draw_char(*s++, x, y, color, scale); x += 8 * scale; }
}

void draw_n(const char* s, int x, int y, u32 color, int max_chars) {
    int n = 0; while (*s && n < max_chars) { draw_char(*s++, x, y, color, 1); x += 8; n++; }
}

int width(const char* s, int scale) { return slen(s) * 8 * scale; }

void draw_c(const char* s, int x, int y, int w, int h, u32 color, int scale) {
    draw(s, x + (w - width(s, scale)) / 2, y + (h - 8 * scale) / 2, color, scale);
}

void draw_int(int v, int x, int y, u32 color, int scale) {
    char b[16]; itoa_(v, b); draw(b, x, y, color, scale);
}

void draw_int_c(int v, int x, int y, int w, int h, u32 color, int scale) {
    char b[16]; itoa_(v, b); draw_c(b, x, y, w, h, color, scale);
}

// Форматированный вывод: [40x40] [text] [40x40]
void draw_truncated(const char* s, int x, int y, int w, u32 color) {
    int max_chars = w / 8;
    if (slen(s) <= max_chars) { draw(s, x, y, color, 1); return; }
    for (int i = 0; i < max_chars - 3; i++) draw_char(s[i], x + i * 8, y, color, 1);
    draw_char('.', x + (max_chars - 3) * 8, y, color, 1);
    draw_char('.', x + (max_chars - 2) * 8, y, color, 1);
    draw_char('.', x + (max_chars - 1) * 8, y, color, 1);
}

